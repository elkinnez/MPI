/**
  * @brief  Lee el sensor BMP280 y envía los datos por ambos UARTs
  * @param  huart_debug: UART para debug (USART1 - PC)
  * @param  huart_esp: UART para ESP (USART2)
  * @retval None
  */
void ReadAndSendData(UART_HandleTypeDef *huart_debug, UART_HandleTypeDef *huart_esp) {
    float temperature, pressure;

    // Leer datos del BMP280 (temperatura y presión compensadas)
    BMP280_ReadData(&temperature, &pressure);

    // Enviar por USART1 (debug - PC) en formato legible
    char debug_msg[64];
    snprintf(debug_msg, sizeof(debug_msg), "READ -> T:%.2f C, P:%.0f Pa\r\n",
             temperature, pressure);
    UART_SendString(huart_debug, debug_msg);

    // Enviar JSON por USART2 (ESP) - Ejercicio 7
    JSON_SendData(huart_esp, temperature, pressure);
}

